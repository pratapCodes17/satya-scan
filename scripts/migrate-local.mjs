import {mkdirSync,readFileSync,writeFileSync} from 'node:fs';
import {resolve} from 'node:path';
import {spawnSync} from 'node:child_process';
import './sites-env.mjs';
const built=JSON.parse(readFileSync('dist/server/wrangler.json','utf8'));
mkdirSync('.sites-runtime',{recursive:true});
const config={name:'satya-scan-local-migrations',compatibility_date:built.compatibility_date,d1_databases:built.d1_databases.map(d=>({...d,migrations_dir:resolve('drizzle')}))};
writeFileSync('.sites-runtime/migrations.json',JSON.stringify(config));
const state=process.argv[2]??'.wrangler/state';
const result=spawnSync(process.execPath,['node_modules/wrangler/bin/wrangler.js','d1','migrations','apply','DB','--local','--config','.sites-runtime/migrations.json','--persist-to',state],{stdio:'inherit'});
process.exit(result.status??1);
